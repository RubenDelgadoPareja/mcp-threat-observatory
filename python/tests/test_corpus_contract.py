"""Contract tests between the TypeScript collector and the Python analysis.

The corpus is generated by `examples/build-corpus.mjs` from labelled synthetic
servers. If a change to a check silently alters what the corpus produces, this
fails. That is the point: the two implementations must agree on the record.
"""

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from mcpobs_analysis.loader import load_corpus
from mcpobs_analysis.schema import ASSERTIONS, CONFIDENCES, SEVERITIES

REPO = Path(__file__).resolve().parents[2]
CORPUS = REPO / "examples" / "corpus"

EXPECTED = {
    "open-readonly": {"AUTH-001"},
    "open-destructive": {"AUTH-001", "TOOL-003"},
    "protected-ok": set(),
    "protected-no-prm": {"AUTH-003", "AUTH-004"},
    "forbidden": {"AUTH-002", "AUTH-003"},
    "poisoned": {"AUTH-001", "TOOL-002"},
    "no-discovery": {"AUTH-001", "PROTO-001"},
    "mixed": {"AUTH-001", "RISK-001", "TOOL-002", "PROTO-001", "TOOL-003"},
    "sparse": {"AUTH-001", "TOOL-001", "TOOL-003"},
}


class CorpusContractTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.snapshots = {snapshot.path.stem: snapshot for snapshot in load_corpus([CORPUS])}

    def test_every_profile_is_present(self) -> None:
        self.assertEqual(set(self.snapshots), set(EXPECTED))

    def test_each_profile_produces_the_expected_checks(self) -> None:
        for profile, expected in EXPECTED.items():
            with self.subTest(profile=profile):
                actual = {finding.check_id for finding in self.snapshots[profile].findings}
                self.assertEqual(actual, expected)

    def test_record_invariants_hold_for_every_finding(self) -> None:
        for profile, snapshot in self.snapshots.items():
            for finding in snapshot.findings:
                with self.subTest(profile=profile, check=finding.check_id):
                    self.assertIn(finding.severity, SEVERITIES)
                    self.assertIn(finding.confidence, CONFIDENCES)
                    self.assertIn(finding.assertion, ASSERTIONS)
                    self.assertEqual(len(finding.fingerprint), 16)
                    self.assertTrue(finding.observation.strip())
                    self.assertTrue(
                        finding.limitations,
                        "a finding without stated limitations is not publishable",
                    )

    def test_inferences_never_claim_certainty(self) -> None:
        for snapshot in self.snapshots.values():
            for finding in snapshot.findings:
                if finding.assertion == "inferred":
                    self.assertIn(
                        finding.confidence,
                        {"moderate", "low"},
                        "an inference must not carry high confidence",
                    )

    def test_every_finding_maps_to_a_known_check_id(self) -> None:
        known = {finding.check_id for snapshot in self.snapshots.values() for finding in snapshot.findings}
        self.assertTrue(known.issubset({f"AUTH-00{i}" for i in range(1, 5)} | {"TOOL-001", "TOOL-002", "TOOL-003", "PROTO-001", "RISK-001"}))


if __name__ == "__main__":
    unittest.main()
